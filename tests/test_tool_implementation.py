"""ToolImplementationGenerator — codegen + sandbox-validated retry loop (P1.17 Phase B).

Real-execution: the generator runs candidate source through the REAL sandbox
(static AST scan + subprocess smoke run), so these tests exercise the full Phase B
path with only the LLM mocked (it returns Python source).
"""

from __future__ import annotations

from pathlib import Path
from unittest.mock import AsyncMock, MagicMock

from mmar_mage.agents.tool_implementation_generator import ToolImplementationGenerator
from mmar_mage.agents.tool_spec_generator import ToolSpec

SPEC = ToolSpec(
    name="add_numbers",
    signature="add_numbers(a: int, b: int) -> int",
    docstring="Add two integers.",
    input_schema={"a": "int", "b": "int"},
    output_schema={"result": "int"},
    dependencies=[],
)

GOOD_SRC = 'def add_numbers(a, b):\n    """Add two integers."""\n    return a + b\n'
BANNED_SRC = "import os\ndef add_numbers(a, b):\n    os.system('echo hi')\n    return a + b\n"
FENCED_SRC = "```python\ndef add_numbers(a, b):\n    return a + b\n```"


def _gen(sources, tmp: Path, max_attempts: int = 3) -> ToolImplementationGenerator:
    llm = MagicMock()
    llm.generate = AsyncMock(side_effect=sources)
    return ToolImplementationGenerator(llm, tools_dir=tmp, max_attempts=max_attempts)


async def test_generate_success_first_attempt(tmp_path: Path):
    gen = _gen([GOOD_SRC], tmp_path)
    impl = await gen.generate(SPEC, query="add two numbers")
    assert impl is not None
    assert impl.attempts == 1
    assert impl.cached is False
    # file written under the configured dir with a provenance header
    p = Path(impl.path)
    assert p.exists() and p.parent == tmp_path
    body = p.read_text()
    assert "Generated by MAGE" in body
    assert "DO NOT COMMIT" in body
    assert "def add_numbers" in body


async def test_generate_retries_after_sandbox_rejection(tmp_path: Path):
    # first candidate uses os.system (static reject), second is clean
    gen = _gen([BANNED_SRC, GOOD_SRC], tmp_path)
    impl = await gen.generate(SPEC)
    assert impl is not None
    assert impl.attempts == 2
    # the repair feedback was injected into the 2nd codegen call's system prompt
    second_call = gen._llm.generate.await_args_list[1]
    assert "REJECTED" in second_call.kwargs["system_prompt"]


async def test_generate_gives_up_after_max_attempts(tmp_path: Path):
    gen = _gen([BANNED_SRC, BANNED_SRC], tmp_path, max_attempts=2)
    impl = await gen.generate(SPEC)
    assert impl is None
    assert gen._llm.generate.await_count == 2


async def test_generate_strips_markdown_fences(tmp_path: Path):
    gen = _gen([FENCED_SRC], tmp_path)
    impl = await gen.generate(SPEC)
    assert impl is not None
    assert "```" not in impl.source


async def test_generate_caches_by_spec_hash(tmp_path: Path):
    gen = _gen([GOOD_SRC], tmp_path)
    first = await gen.generate(SPEC)
    assert first is not None and first.cached is False

    # second generator, same spec + dir → cache hit, no LLM call
    gen2 = _gen([GOOD_SRC], tmp_path)
    second = await gen2.generate(SPEC)
    assert second is not None
    assert second.cached is True
    gen2._llm.generate.assert_not_called()


async def test_regenerate_flag_bypasses_cache(tmp_path: Path):
    gen = _gen([GOOD_SRC], tmp_path)
    await gen.generate(SPEC)
    gen2 = _gen([GOOD_SRC], tmp_path)
    out = await gen2.generate(SPEC, regenerate=True)
    assert out is not None and out.cached is False
    gen2._llm.generate.assert_awaited_once()
