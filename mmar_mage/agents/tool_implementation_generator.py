"""ToolImplementationGenerator — codegen + sandbox-validated retry loop (P1.17 Phase B).

Takes a :class:`~mmar_mage.agents.tool_spec_generator.ToolSpec` and produces a
validated Python module on disk (``~/.mage/generated_tools/<name>_<hash>.py``, a
user-config dir — never the repo). Each candidate is checked by the
:mod:`mmar_mage.security.sandbox` (static AST scan, then a resource-limited
subprocess smoke run); on failure the trace is fed back to the LLM and it retries,
up to ``max_attempts``. Results cache by a content hash of the spec.

Generation runs no code from the model directly — only the sandbox executes it,
in an isolated subprocess. Gated behind ``enable_tool_synthesis`` upstream.
"""

from __future__ import annotations

import datetime
import hashlib
import json
import logging
from pathlib import Path

from pydantic import BaseModel

from ..generated_tool_index import DEFAULT_TOOLS_DIR, register_tool
from ..llm import LLMClient
from ..prompts import TOOL_IMPL_PROMPT
from ..security import validate_tool_source
from .tool_spec_generator import ToolSpec

logger = logging.getLogger(__name__)

STAGE = "tool_implementation"


class ToolImplementation(BaseModel):
    """A validated, on-disk tool implementation."""

    spec_name: str
    path: str
    source: str
    attempts: int = 1
    cached: bool = False


def _strip_code_fences(text: str) -> str:
    """Remove a leading/trailing markdown code fence if the model added one."""
    text = text.strip()
    if text.startswith("```"):
        # drop first fence line and a trailing fence
        lines = text.splitlines()
        if lines and lines[0].lstrip().startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip().startswith("```"):
            lines = lines[:-1]
        text = "\n".join(lines)
    return text.strip()


def _provenance_header(spec: ToolSpec, query: str, today: str) -> str:
    q = (query or "").replace("\n", " ")[:120]
    return (
        f"# Generated by MAGE on {today} from query: {q}\n"
        f"# Tool: {spec.name}\n"
        "# DO NOT COMMIT — regenerate via MAGE (synthesized, sandbox-validated code).\n\n"
    )


class ToolImplementationGenerator:
    """Generate + sandbox-validate a tool implementation, with a repair retry loop.

    Parameters
    ----------
    llm : LLMClient
        Client for code generation.
    tools_dir : Path | None
        Output directory (defaults to ``~/.mage/generated_tools``).
    max_attempts : int
        Codegen attempts before giving up (default 3).
    """

    def __init__(self, llm: LLMClient, tools_dir: Path | None = None, max_attempts: int = 3) -> None:
        self._llm = llm
        self._dir = tools_dir or DEFAULT_TOOLS_DIR
        self._max_attempts = max(1, max_attempts)

    @staticmethod
    def _spec_hash(spec: ToolSpec) -> str:
        payload = json.dumps(spec.model_dump(), sort_keys=True, ensure_ascii=False)
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:8]

    def _target_path(self, spec: ToolSpec) -> Path:
        return self._dir / f"{spec.name}_{self._spec_hash(spec)}.py"

    async def generate(self, spec: ToolSpec, query: str = "", regenerate: bool = False) -> ToolImplementation | None:
        """Produce a validated implementation for ``spec`` (or ``None`` if all attempts fail).

        Returns a cached result when a prior validated file exists for the same
        spec hash, unless ``regenerate=True``.
        """
        path = self._target_path(spec)
        if path.exists() and not regenerate:
            logger.info("ToolImplementation: cache hit for %r at %s", spec.name, path)
            return ToolImplementation(
                spec_name=spec.name, path=str(path), source=path.read_text(encoding="utf-8"), cached=True
            )

        allowed = set(spec.dependencies)
        spec_block = json.dumps(spec.model_dump(), ensure_ascii=False, indent=2)
        repair_feedback = ""

        for attempt in range(1, self._max_attempts + 1):
            system = TOOL_IMPL_PROMPT.format(
                func_name=spec.name,
                repair_feedback=repair_feedback,
            )
            try:
                raw = await self._llm.generate(
                    system_prompt=system,
                    user_prompt=f"Tool spec:\n{spec_block}",
                    json_mode=False,
                    stage=STAGE,
                )
            except Exception as exc:
                logger.warning("ToolImplementation: codegen call failed on attempt %d: %s", attempt, exc)
                return None

            source = _strip_code_fences(raw)
            report = validate_tool_source(
                source,
                spec.name,
                allowed_imports=allowed,
                input_schema=spec.input_schema,
                examples=[ex.model_dump() for ex in spec.examples],
            )
            if report.ok:
                final = _provenance_header(spec, query, datetime.date.today().isoformat()) + source + "\n"
                self._dir.mkdir(parents=True, exist_ok=True)
                path.write_text(final, encoding="utf-8")
                if spec.examples:
                    # WP-8: persist the behaviour cases as a regression set next to
                    # the module so a future regenerate can re-check the same spec.
                    tests_path = self._dir / f"{spec.name}_{self._spec_hash(spec)}_tests.json"
                    tests_path.write_text(
                        json.dumps([ex.model_dump() for ex in spec.examples], ensure_ascii=False, indent=2),
                        encoding="utf-8",
                    )
                # WP-9: register in the local index so the next run's
                # CapabilityLookupAgent surfaces it instead of re-synthesizing.
                register_tool(
                    self._dir,
                    {
                        "name": spec.name,
                        "signature": spec.signature,
                        "description": spec.docstring,
                        "input_schema": spec.input_schema,
                        "output_schema": spec.output_schema,
                        "path": str(path),
                        "source": "generated",
                        "examples": [ex.model_dump() for ex in spec.examples],
                    },
                )
                logger.info("ToolImplementation: %r validated on attempt %d → %s", spec.name, attempt, path)
                return ToolImplementation(spec_name=spec.name, path=str(path), source=final, attempts=attempt)

            feedback = report.feedback()
            logger.info("ToolImplementation: attempt %d for %r rejected: %s", attempt, spec.name, feedback)
            repair_feedback = f"Your previous attempt was REJECTED. Fix it and try again.\nReason: {feedback}\n\n"

        logger.warning("ToolImplementation: gave up on %r after %d attempts", spec.name, self._max_attempts)
        return None
